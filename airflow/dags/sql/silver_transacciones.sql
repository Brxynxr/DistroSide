-- Transformación Bronze -> Silver en Snowflake
-- Reglas explícitas de calidad:
-- 1. Estandarización de TIPO, CATEGORIA y AREA (UPPER + TRIM).
-- 2. Parseo explícito de FECHA según patrón (YYYY-MM-DD o DD/MM/YYYY).
-- 3. Deduplicación determinista por ID_TRANSACCION.
-- 4. Ningún registro se descarta silenciosamente: nulos, inválidos y duplicados
--    se registran en SILVER.TRANSACCIONES_RECHAZADOS con su MOTIVO_RECHAZO.

CREATE OR REPLACE TABLE DATAFINANCE.SILVER.TRANSACCIONES AS
WITH normalizado AS (
    SELECT
        TRIM(ID_TRANSACCION) AS ID_TRANSACCION,
        CASE
            WHEN REGEXP_LIKE(TRIM(FECHA), '^[0-9]{4}-[0-9]{2}-[0-9]{2}$')
                THEN TRY_TO_DATE(TRIM(FECHA), 'YYYY-MM-DD')
            WHEN REGEXP_LIKE(TRIM(FECHA), '^[0-9]{2}/[0-9]{2}/[0-9]{4}$')
                THEN TRY_TO_DATE(TRIM(FECHA), 'DD/MM/YYYY')
            ELSE NULL
        END AS FECHA,
        UPPER(TRIM(TIPO)) AS TIPO,
        UPPER(TRIM(CATEGORIA)) AS CATEGORIA,
        UPPER(TRIM(AREA)) AS AREA,
        ROUND(MONTO, 2)::NUMBER(14, 2) AS MONTO,
        TRIM(DESCRIPCION) AS DESCRIPCION,
        FECHA AS FECHA_ORIGINAL,
        ROW_NUMBER() OVER (
            PARTITION BY TRIM(ID_TRANSACCION)
            ORDER BY IFF(MONTO IS NULL, 1, 0), FECHA
        ) AS RN
    FROM DATAFINANCE.BRONZE.TRANSACCIONES
)
SELECT
    ID_TRANSACCION,
    FECHA,
    YEAR(FECHA) AS ANIO,
    DATE_TRUNC('MONTH', FECHA) AS MES,
    TO_CHAR(FECHA, 'YYYY-MM') AS ANIO_MES,
    TIPO,
    CATEGORIA,
    AREA,
    MONTO,
    DESCRIPCION,
    FECHA_ORIGINAL,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS CARGADO_SILVER_EN
FROM normalizado
WHERE RN = 1
  AND ID_TRANSACCION IS NOT NULL
  AND ID_TRANSACCION <> ''
  AND FECHA IS NOT NULL
  AND MONTO IS NOT NULL
  AND MONTO > 0
  AND TIPO IN ('INGRESO', 'GASTO');

CREATE OR REPLACE TABLE DATAFINANCE.SILVER.TRANSACCIONES_RECHAZADOS AS
WITH evaluado AS (
    SELECT
        ID_TRANSACCION,
        FECHA AS FECHA_ORIGINAL,
        CASE
            WHEN REGEXP_LIKE(TRIM(FECHA), '^[0-9]{4}-[0-9]{2}-[0-9]{2}$')
                THEN TRY_TO_DATE(TRIM(FECHA), 'YYYY-MM-DD')
            WHEN REGEXP_LIKE(TRIM(FECHA), '^[0-9]{2}/[0-9]{2}/[0-9]{4}$')
                THEN TRY_TO_DATE(TRIM(FECHA), 'DD/MM/YYYY')
            ELSE NULL
        END AS FECHA_PARSEADA,
        UPPER(TRIM(TIPO)) AS TIPO_NORM,
        UPPER(TRIM(CATEGORIA)) AS CATEGORIA_NORM,
        UPPER(TRIM(AREA)) AS AREA_NORM,
        MONTO,
        DESCRIPCION,
        ROW_NUMBER() OVER (
            PARTITION BY TRIM(ID_TRANSACCION)
            ORDER BY IFF(MONTO IS NULL, 1, 0), FECHA
        ) AS RN
    FROM DATAFINANCE.BRONZE.TRANSACCIONES
),
clasificado AS (
    SELECT
        *,
        CASE
            WHEN TRIM(ID_TRANSACCION) IS NULL OR TRIM(ID_TRANSACCION) = '' THEN 'ID_NULO'
            WHEN RN > 1 THEN 'DUPLICADO'
            WHEN FECHA_PARSEADA IS NULL THEN 'FECHA_INVALIDA'
            WHEN MONTO IS NULL OR MONTO <= 0 THEN 'MONTO_NULO_O_NO_POSITIVO'
            WHEN TIPO_NORM NOT IN ('INGRESO', 'GASTO') THEN 'TIPO_INVALIDO'
            ELSE NULL
        END AS MOTIVO_RECHAZO
    FROM evaluado
)
SELECT
    ID_TRANSACCION,
    FECHA_ORIGINAL,
    TIPO_NORM AS TIPO,
    CATEGORIA_NORM AS CATEGORIA,
    AREA_NORM AS AREA,
    MONTO,
    DESCRIPCION,
    MOTIVO_RECHAZO,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS REGISTRADO_EN
FROM clasificado
WHERE MOTIVO_RECHAZO IS NOT NULL;
