-- Script SQL para el Centinela Semanal de Sobrecostos Operativos (DataFinance AI).
-- Principio fundamental: SQL calcula (Run-rate y Proyección); la IA explica.
-- Evalúa el ritmo de gasto acumulado en el mes en curso y proyecta desviaciones atípicas.

CREATE SCHEMA IF NOT EXISTS DATAFINANCE.PUBLIC;

-- 1. Tabla de alertas preventivas del Centinela Operativo
CREATE TABLE IF NOT EXISTS DATAFINANCE.PUBLIC.ALERTAS_CENTINELA (
    ID_ALERTA NUMBER AUTOINCREMENT PRIMARY KEY,
    FECHA_EVALUACION TIMESTAMP_NTZ NOT NULL,
    PERIODO VARCHAR(7) NOT NULL,
    FECHA_CORTE DATE NOT NULL,
    DIAS_TRANSCURRIDOS NUMBER NOT NULL,
    DIAS_TOTALES_MES NUMBER NOT NULL,
    CATEGORIA VARCHAR(50) NOT NULL,
    AREA VARCHAR(50) NOT NULL,
    GASTO_ACUMULADO NUMBER(14,2) NOT NULL,
    PROMEDIO_HISTORICO_MENSUAL NUMBER(14,2) NOT NULL,
    PORCENTAJE_CONSUMIDO NUMBER(7,2) NOT NULL,
    PROYECCION_FIN_MES NUMBER(14,2) NOT NULL,
    DESVIO_PROYECTADO_PCT NUMBER(7,2) NOT NULL,
    NIVEL_RIESGO VARCHAR(20) NOT NULL, -- 'CRITICO', 'ALTO', 'MODERADO'
    DIAGNOSTICO_IA VARCHAR,
    TRANSACCIONES_CRITICAS VARIANT,
    ESTADO VARCHAR(20) DEFAULT 'ACTIVA' -- 'ACTIVA', 'MITIGADA', 'ARCHIVADA'
);

-- 2. Consulta analítica base para cálculo de Run-Rate y Proyección
-- Esta lógica compara el ritmo de gasto actual contra el histórico mensual por categoría
CREATE OR REPLACE VIEW DATAFINANCE.PUBLIC.V_CENTINELA_RUN_RATE AS
WITH meses_completos AS (
    SELECT MES
    FROM DATAFINANCE.PUBLIC.TRANSACCIONES
    GROUP BY MES
    HAVING DAY(MAX(FECHA)) >= 28
),
promedios_historicos AS (
    SELECT
        k.TIPO,
        k.CATEGORIA,
        ROUND(AVG(k.MONTO_TOTAL), 2) AS PROMEDIO_HISTORICO,
        ROUND(STDDEV_SAMP(k.MONTO_TOTAL), 2) AS STD_HISTORICO
    FROM DATAFINANCE.PUBLIC.KPI_CATEGORIA_MENSUAL k
    INNER JOIN meses_completos mc ON k.MES = mc.MES
    WHERE k.TIPO = 'GASTO'
    GROUP BY k.TIPO, k.CATEGORIA
),
mes_actual AS (
    SELECT
        ANIO_MES,
        MES,
        MAX(FECHA) AS FECHA_CORTE,
        DAY(MAX(FECHA)) AS DIAS_TRANSCURRIDOS,
        DAY(LAST_DAY(MAX(FECHA))) AS DIAS_TOTALES_MES
    FROM DATAFINANCE.PUBLIC.TRANSACCIONES
    GROUP BY ANIO_MES, MES
    ORDER BY MES DESC
    LIMIT 1
),
gasto_actual_categoria AS (
    SELECT
        t.ANIO_MES,
        t.MES,
        t.CATEGORIA,
        t.AREA,
        ROUND(SUM(t.MONTO), 2) AS GASTO_ACUMULADO,
        COUNT(*) AS TOTAL_TRANSACCIONES
    FROM DATAFINANCE.PUBLIC.TRANSACCIONES t
    INNER JOIN mes_actual ma ON t.MES = ma.MES
    WHERE t.TIPO = 'GASTO'
    GROUP BY t.ANIO_MES, t.MES, t.CATEGORIA, t.AREA
)
SELECT
    g.ANIO_MES AS PERIODO,
    ma.FECHA_CORTE,
    ma.DIAS_TRANSCURRIDOS,
    ma.DIAS_TOTALES_MES,
    g.CATEGORIA,
    g.AREA,
    g.GASTO_ACUMULADO,
    g.TOTAL_TRANSACCIONES,
    p.PROMEDIO_HISTORICO,
    ROUND((g.GASTO_ACUMULADO / NULLIF(p.PROMEDIO_HISTORICO, 0)) * 100, 2) AS PORCENTAJE_CONSUMIDO,
    ROUND((g.GASTO_ACUMULADO / NULLIF(ma.DIAS_TRANSCURRIDOS, 0)) * ma.DIAS_TOTALES_MES, 2) AS PROYECCION_FIN_MES,
    ROUND(
        (
            ((g.GASTO_ACUMULADO / NULLIF(ma.DIAS_TRANSCURRIDOS, 0)) * ma.DIAS_TOTALES_MES - p.PROMEDIO_HISTORICO)
            / NULLIF(p.PROMEDIO_HISTORICO, 0)
        ) * 100,
        2
    ) AS DESVIO_PROYECTADO_PCT,
    CASE
        WHEN ((g.GASTO_ACUMULADO / NULLIF(ma.DIAS_TRANSCURRIDOS, 0)) * ma.DIAS_TOTALES_MES) >= (p.PROMEDIO_HISTORICO * 1.5)
             OR (ma.DIAS_TRANSCURRIDOS <= 15 AND (g.GASTO_ACUMULADO / NULLIF(p.PROMEDIO_HISTORICO, 0)) >= 0.70)
             THEN 'CRITICO'
        WHEN ((g.GASTO_ACUMULADO / NULLIF(ma.DIAS_TRANSCURRIDOS, 0)) * ma.DIAS_TOTALES_MES) >= (p.PROMEDIO_HISTORICO * 1.25)
             OR (ma.DIAS_TRANSCURRIDOS <= 15 AND (g.GASTO_ACUMULADO / NULLIF(p.PROMEDIO_HISTORICO, 0)) >= 0.55)
             THEN 'ALTO'
        WHEN ((g.GASTO_ACUMULADO / NULLIF(ma.DIAS_TRANSCURRIDOS, 0)) * ma.DIAS_TOTALES_MES) >= (p.PROMEDIO_HISTORICO * 1.15)
             THEN 'MODERADO'
        ELSE 'NORMAL'
    END AS NIVEL_RIESGO
FROM gasto_actual_categoria g
INNER JOIN mes_actual ma ON g.MES = ma.MES
LEFT JOIN promedios_historicos p ON g.CATEGORIA = p.CATEGORIA
ORDER BY DESVIO_PROYECTADO_PCT DESC;
