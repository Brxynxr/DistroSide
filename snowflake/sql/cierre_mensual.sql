-- Script SQL para Cierre Financiero Mensual Automatizado de DataFinance AI.
-- Principio fundamental: SQL calcula; la IA explica.
-- Recalcula KPI_MENSUAL, ANOMALIAS y garantiza la existencia de AUDITORIA_CIERRES.

CREATE SCHEMA IF NOT EXISTS DATAFINANCE.PUBLIC;

-- 1. Tabla de auditoría y control de cierres mensuales automatizados
CREATE TABLE IF NOT EXISTS DATAFINANCE.PUBLIC.AUDITORIA_CIERRES (
    ID_CIERRE NUMBER AUTOINCREMENT PRIMARY KEY,
    MES_CERRADO VARCHAR(7) NOT NULL,
    FECHA_EJECUCION TIMESTAMP_NTZ NOT NULL,
    ESTADO VARCHAR(30) NOT NULL,
    TOTAL_TRANSACCIONES NUMBER,
    INGRESOS NUMBER(14,2),
    GASTOS NUMBER(14,2),
    UTILIDAD NUMBER(14,2),
    MARGEN_PCT NUMBER(7,2),
    TOTAL_ANOMALIAS NUMBER DEFAULT 0,
    ID_REPORTE NUMBER,
    NOMBRE_ARCHIVO_PDF VARCHAR(255),
    EJECUTADO_POR VARCHAR(50) DEFAULT 'AUTOMATION',
    MENSAJE VARCHAR(500)
);

-- 2. Recálculo integral de KPI_MENSUAL sobre DATAFINANCE.PUBLIC.TRANSACCIONES
CREATE OR REPLACE TABLE DATAFINANCE.PUBLIC.KPI_MENSUAL AS
WITH agregado AS (
    SELECT
        MES,
        ANIO_MES,
        YEAR(MES) AS ANIO,
        MONTH(MES) AS NUMERO_MES,
        COUNT(*) AS TOTAL_TRANSACCIONES,
        ROUND(SUM(IFF(TIPO = 'INGRESO', MONTO, 0)), 2) AS INGRESOS,
        ROUND(SUM(IFF(TIPO = 'GASTO', MONTO, 0)), 2) AS GASTOS
    FROM DATAFINANCE.PUBLIC.TRANSACCIONES
    GROUP BY MES, ANIO_MES, YEAR(MES), MONTH(MES)
),
con_utilidad AS (
    SELECT
        MES,
        ANIO_MES,
        ANIO,
        NUMERO_MES,
        TOTAL_TRANSACCIONES,
        INGRESOS,
        GASTOS,
        ROUND(INGRESOS - GASTOS, 2) AS UTILIDAD,
        IFF(
            INGRESOS = 0,
            0.00,
            ROUND((INGRESOS - GASTOS) / INGRESOS * 100, 2)
        ) AS MARGEN_PCT
    FROM agregado
),
con_anterior AS (
    SELECT
        *,
        LAG(INGRESOS) OVER (ORDER BY MES) AS INGRESOS_MES_ANTERIOR,
        LAG(GASTOS) OVER (ORDER BY MES) AS GASTOS_MES_ANTERIOR,
        LAG(UTILIDAD) OVER (ORDER BY MES) AS UTILIDAD_MES_ANTERIOR
    FROM con_utilidad
)
SELECT
    MES,
    ANIO_MES,
    ANIO,
    NUMERO_MES,
    TOTAL_TRANSACCIONES,
    INGRESOS,
    GASTOS,
    UTILIDAD,
    MARGEN_PCT,
    INGRESOS_MES_ANTERIOR,
    GASTOS_MES_ANTERIOR,
    UTILIDAD_MES_ANTERIOR,
    ROUND(INGRESOS - INGRESOS_MES_ANTERIOR, 2) AS VAR_INGRESOS_ABS,
    IFF(
        INGRESOS_MES_ANTERIOR IS NULL OR INGRESOS_MES_ANTERIOR = 0,
        NULL,
        ROUND((INGRESOS - INGRESOS_MES_ANTERIOR) / INGRESOS_MES_ANTERIOR * 100, 2)
    ) AS VAR_INGRESOS_PCT,
    ROUND(GASTOS - GASTOS_MES_ANTERIOR, 2) AS VAR_GASTOS_ABS,
    IFF(
        GASTOS_MES_ANTERIOR IS NULL OR GASTOS_MES_ANTERIOR = 0,
        NULL,
        ROUND((GASTOS - GASTOS_MES_ANTERIOR) / GASTOS_MES_ANTERIOR * 100, 2)
    ) AS VAR_GASTOS_PCT,
    ROUND(UTILIDAD - UTILIDAD_MES_ANTERIOR, 2) AS VAR_UTILIDAD_ABS,
    IFF(
        UTILIDAD_MES_ANTERIOR IS NULL OR UTILIDAD_MES_ANTERIOR = 0,
        NULL,
        ROUND((UTILIDAD - UTILIDAD_MES_ANTERIOR) / ABS(UTILIDAD_MES_ANTERIOR) * 100, 2)
    ) AS VAR_UTILIDAD_PCT,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS ACTUALIZADO_EN
FROM con_anterior
ORDER BY MES;

-- 3. Detección estadística de anomalías (Z-score) sobre periodos completos
CREATE OR REPLACE TABLE DATAFINANCE.PUBLIC.ANOMALIAS AS
WITH meses_completos AS (
    SELECT
        MES,
        MAX(FECHA) AS ULTIMA_FECHA_MES
    FROM DATAFINANCE.PUBLIC.TRANSACCIONES
    GROUP BY MES
    HAVING DAY(MAX(FECHA)) >= 28
),
stats_categoria AS (
    SELECT
        k.MES,
        k.ANIO_MES,
        k.TIPO,
        k.CATEGORIA,
        k.MONTO_TOTAL,
        AVG(k.MONTO_TOTAL) OVER (PARTITION BY k.TIPO, k.CATEGORIA) AS PROMEDIO_HISTORICO,
        STDDEV_SAMP(k.MONTO_TOTAL) OVER (PARTITION BY k.TIPO, k.CATEGORIA) AS DESV_ESTANDAR
    FROM DATAFINANCE.PUBLIC.KPI_CATEGORIA_MENSUAL k
    INNER JOIN meses_completos mc ON k.MES = mc.MES
),
anomalias_categoria AS (
    SELECT
        MES,
        ANIO_MES,
        'CATEGORIA' AS NIVEL,
        TIPO,
        CATEGORIA,
        MONTO_TOTAL AS VALOR_OBSERVADO,
        ROUND(PROMEDIO_HISTORICO, 2) AS VALOR_ESPERADO,
        ROUND((MONTO_TOTAL - PROMEDIO_HISTORICO) / NULLIF(DESV_ESTANDAR, 0), 2) AS Z_SCORE,
        IFF(MONTO_TOTAL > PROMEDIO_HISTORICO, 'PICO_ATIPICO', 'CAIDA_ATIPICA') AS TIPO_ANOMALIA,
        CONCAT(
            TIPO, ' en ', CATEGORIA, ' fue ',
            ROUND(MONTO_TOTAL / NULLIF(PROMEDIO_HISTORICO, 0), 2),
            'x respecto al promedio histórico mensual'
        ) AS MOTIVO
    FROM stats_categoria
    WHERE ABS((MONTO_TOTAL - PROMEDIO_HISTORICO) / NULLIF(DESV_ESTANDAR, 0)) >= 2.5
),
stats_mensual AS (
    SELECT
        k.MES,
        k.ANIO_MES,
        k.INGRESOS,
        AVG(k.INGRESOS) OVER () AS PROM_INGRESOS,
        STDDEV_SAMP(k.INGRESOS) OVER () AS STD_INGRESOS,
        k.UTILIDAD,
        AVG(k.UTILIDAD) OVER () AS PROM_UTILIDAD,
        STDDEV_SAMP(k.UTILIDAD) OVER () AS STD_UTILIDAD
    FROM DATAFINANCE.PUBLIC.KPI_MENSUAL k
    INNER JOIN meses_completos mc ON k.MES = mc.MES
),
anomalias_globales AS (
    SELECT
        MES,
        ANIO_MES,
        'MENSUAL' AS NIVEL,
        'INGRESO' AS TIPO,
        'TOTAL_INGRESOS' AS CATEGORIA,
        INGRESOS AS VALOR_OBSERVADO,
        ROUND(PROM_INGRESOS, 2) AS VALOR_ESPERADO,
        ROUND((INGRESOS - PROM_INGRESOS) / NULLIF(STD_INGRESOS, 0), 2) AS Z_SCORE,
        IFF(INGRESOS > PROM_INGRESOS, 'PICO_ATIPICO', 'CAIDA_ATIPICA') AS TIPO_ANOMALIA,
        CONCAT(
            'Ingresos totales del mes (', ROUND(INGRESOS / 1e6, 2),
            ' M COP) frente a promedio histórico (', ROUND(PROM_INGRESOS / 1e6, 2), ' M COP)'
        ) AS MOTIVO
    FROM stats_mensual
    WHERE ABS((INGRESOS - PROM_INGRESOS) / NULLIF(STD_INGRESOS, 0)) >= 2.5
)
SELECT
    MES,
    ANIO_MES,
    NIVEL,
    TIPO,
    CATEGORIA,
    VALOR_OBSERVADO,
    VALOR_ESPERADO,
    Z_SCORE,
    TIPO_ANOMALIA,
    MOTIVO,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS DETECTADO_EN
FROM (
    SELECT * FROM anomalias_categoria
    UNION ALL
    SELECT * FROM anomalias_globales
)
ORDER BY MES, ABS(Z_SCORE) DESC;
