-- Validación de calidad sobre DATAFINANCE.SILVER.TRANSACCIONES
-- Compatible con SQLCheckOperator de Airflow (una sola fila booleana).

SELECT
    COUNT(*) > 0
    AND COUNT(*) = COUNT(DISTINCT ID_TRANSACCION)
    AND SUM(IFF(FECHA IS NULL, 1, 0)) = 0
    AND SUM(IFF(MONTO IS NULL OR MONTO <= 0, 1, 0)) = 0
    AND SUM(IFF(TIPO NOT IN ('INGRESO', 'GASTO'), 1, 0)) = 0
    AND SUM(IFF(CATEGORIA <> UPPER(TRIM(CATEGORIA)), 1, 0)) = 0
    AND SUM(IFF(AREA <> UPPER(TRIM(AREA)), 1, 0)) = 0
    AS SILVER_VALIDA
FROM DATAFINANCE.SILVER.TRANSACCIONES;
