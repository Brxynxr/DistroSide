-- Script SQL para el Cuadre Diario de Ventas y Monitoreo de Liquidez (DataFinance AI).
-- Principio fundamental: SQL calcula (Ventas Contado vs Crédito y Ratios); la IA explica.
-- Evalúa el recaudo diario al cierre de ruta para alertar riesgos de flujo de caja en tesorería.

CREATE SCHEMA IF NOT EXISTS DATAFINANCE.PUBLIC;

-- 1. Tabla de auditoría y bitácora de cuadres diarios de liquidez
CREATE TABLE IF NOT EXISTS DATAFINANCE.PUBLIC.CUADRE_DIARIO_LIQUIDEZ (
    ID_CUADRE NUMBER AUTOINCREMENT PRIMARY KEY,
    FECHA DATE NOT NULL,
    TOTAL_VENTAS NUMBER(14,2) NOT NULL,
    VENTAS_CONTADO NUMBER(14,2) NOT NULL,
    VENTAS_CREDITO NUMBER(14,2) NOT NULL,
    SERVICIOS NUMBER(14,2) NOT NULL,
    RATIO_CONTADO_PCT NUMBER(7,2) NOT NULL,
    RATIO_CREDITO_PCT NUMBER(7,2) NOT NULL,
    ESTADO_LIQUIDEZ VARCHAR(20) NOT NULL, -- 'OPTIMA', 'ADVERTENCIA', 'CRITICA'
    TOTAL_TRANSACCIONES NUMBER NOT NULL,
    SINTESIS_TESORERIA VARCHAR,
    REGISTRADO_EN TIMESTAMP_NTZ NOT NULL,
    EJECUTADO_POR VARCHAR(50) DEFAULT 'AUTOMATION_DAILY'
);

-- 2. Vista analítica para cuadre consolidado diario
CREATE OR REPLACE VIEW DATAFINANCE.PUBLIC.V_CUADRE_DIARIO_CONSOLIDADO AS
WITH ventas_dia AS (
    SELECT
        FECHA,
        COUNT(*) AS TOTAL_TRANSACCIONES,
        ROUND(SUM(IFF(CATEGORIA = 'VENTA CONTADO', MONTO, 0)), 2) AS VENTAS_CONTADO,
        ROUND(SUM(IFF(CATEGORIA = 'VENTA CREDITO', MONTO, 0)), 2) AS VENTAS_CREDITO,
        ROUND(SUM(IFF(CATEGORIA = 'SERVICIOS', MONTO, 0)), 2) AS SERVICIOS,
        ROUND(SUM(MONTO), 2) AS TOTAL_VENTAS
    FROM DATAFINANCE.PUBLIC.TRANSACCIONES
    WHERE TIPO = 'INGRESO'
    GROUP BY FECHA
)
SELECT
    FECHA,
    TOTAL_VENTAS,
    VENTAS_CONTADO,
    VENTAS_CREDITO,
    SERVICIOS,
    TOTAL_TRANSACCIONES,
    ROUND((VENTAS_CONTADO / NULLIF(TOTAL_VENTAS, 0)) * 100, 2) AS RATIO_CONTADO_PCT,
    ROUND((VENTAS_CREDITO / NULLIF(TOTAL_VENTAS, 0)) * 100, 2) AS RATIO_CREDITO_PCT,
    ROUND((SERVICIOS / NULLIF(TOTAL_VENTAS, 0)) * 100, 2) AS RATIO_SERVICIOS_PCT,
    CASE
        WHEN (VENTAS_CONTADO / NULLIF(TOTAL_VENTAS, 0)) >= 0.45 THEN 'OPTIMA'
        WHEN (VENTAS_CONTADO / NULLIF(TOTAL_VENTAS, 0)) >= 0.35 THEN 'ADVERTENCIA'
        ELSE 'CRITICA'
    END AS ESTADO_LIQUIDEZ
FROM ventas_dia
ORDER BY FECHA DESC;
