-- Capa Gold: indicadores financieros mensuales, por categoría y por área.
-- Consume exclusivamente DATAFINANCE.SILVER.TRANSACCIONES.

CREATE OR REPLACE TABLE DATAFINANCE.GOLD.KPI_MENSUAL AS
WITH agregado AS (
    SELECT
        MES,
        ANIO_MES,
        YEAR(MES) AS ANIO,
        MONTH(MES) AS NUMERO_MES,
        COUNT(*) AS TOTAL_TRANSACCIONES,
        ROUND(SUM(IFF(TIPO = 'INGRESO', MONTO, 0)), 2) AS INGRESOS,
        ROUND(SUM(IFF(TIPO = 'GASTO', MONTO, 0)), 2) AS GASTOS
    FROM DATAFINANCE.SILVER.TRANSACCIONES
    GROUP BY MES, ANIO_MES, YEAR(MES), MONTH(MES)
),
con_utilidad AS (
    SELECT
        MES,
        ANIO_MES,
        ANIO,
        NUMERO_MES,
        TOTAL_TRANSACCIONES,
        INGRESOS,
        GASTOS,
        ROUND(INGRESOS - GASTOS, 2) AS UTILIDAD,
        IFF(
            INGRESOS = 0,
            0.00,
            ROUND((INGRESOS - GASTOS) / INGRESOS * 100, 2)
        ) AS MARGEN_PCT
    FROM agregado
),
con_anterior AS (
    SELECT
        *,
        LAG(INGRESOS) OVER (ORDER BY MES) AS INGRESOS_MES_ANTERIOR,
        LAG(GASTOS) OVER (ORDER BY MES) AS GASTOS_MES_ANTERIOR,
        LAG(UTILIDAD) OVER (ORDER BY MES) AS UTILIDAD_MES_ANTERIOR
    FROM con_utilidad
)
SELECT
    MES,
    ANIO_MES,
    ANIO,
    NUMERO_MES,
    TOTAL_TRANSACCIONES,
    INGRESOS,
    GASTOS,
    UTILIDAD,
    MARGEN_PCT,
    INGRESOS_MES_ANTERIOR,
    GASTOS_MES_ANTERIOR,
    UTILIDAD_MES_ANTERIOR,
    ROUND(INGRESOS - INGRESOS_MES_ANTERIOR, 2) AS VAR_INGRESOS_ABS,
    IFF(
        INGRESOS_MES_ANTERIOR IS NULL OR INGRESOS_MES_ANTERIOR = 0,
        NULL,
        ROUND((INGRESOS - INGRESOS_MES_ANTERIOR) / INGRESOS_MES_ANTERIOR * 100, 2)
    ) AS VAR_INGRESOS_PCT,
    ROUND(GASTOS - GASTOS_MES_ANTERIOR, 2) AS VAR_GASTOS_ABS,
    IFF(
        GASTOS_MES_ANTERIOR IS NULL OR GASTOS_MES_ANTERIOR = 0,
        NULL,
        ROUND((GASTOS - GASTOS_MES_ANTERIOR) / GASTOS_MES_ANTERIOR * 100, 2)
    ) AS VAR_GASTOS_PCT,
    ROUND(UTILIDAD - UTILIDAD_MES_ANTERIOR, 2) AS VAR_UTILIDAD_ABS,
    IFF(
        UTILIDAD_MES_ANTERIOR IS NULL OR UTILIDAD_MES_ANTERIOR = 0,
        NULL,
        ROUND((UTILIDAD - UTILIDAD_MES_ANTERIOR) / ABS(UTILIDAD_MES_ANTERIOR) * 100, 2)
    ) AS VAR_UTILIDAD_PCT,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS ACTUALIZADO_EN
FROM con_anterior
ORDER BY MES;

-- Vista por categoría y mes (base para análisis por categoría y detección de anomalías)
CREATE OR REPLACE VIEW DATAFINANCE.GOLD.KPI_CATEGORIA_MENSUAL AS
WITH agregado AS (
    SELECT
        MES,
        ANIO_MES,
        YEAR(MES) AS ANIO,
        MONTH(MES) AS NUMERO_MES,
        TIPO,
        CATEGORIA,
        COUNT(*) AS TOTAL_TRANSACCIONES,
        ROUND(SUM(MONTO), 2) AS MONTO_TOTAL
    FROM DATAFINANCE.SILVER.TRANSACCIONES
    GROUP BY MES, ANIO_MES, YEAR(MES), MONTH(MES), TIPO, CATEGORIA
),
con_anterior AS (
    SELECT
        *,
        LAG(MONTO_TOTAL) OVER (
            PARTITION BY TIPO, CATEGORIA
            ORDER BY MES
        ) AS MONTO_MES_ANTERIOR
    FROM agregado
)
SELECT
    MES,
    ANIO_MES,
    ANIO,
    NUMERO_MES,
    TIPO,
    CATEGORIA,
    TOTAL_TRANSACCIONES,
    MONTO_TOTAL,
    MONTO_MES_ANTERIOR,
    ROUND(MONTO_TOTAL - MONTO_MES_ANTERIOR, 2) AS VAR_ABS,
    IFF(
        MONTO_MES_ANTERIOR IS NULL OR MONTO_MES_ANTERIOR = 0,
        NULL,
        ROUND((MONTO_TOTAL - MONTO_MES_ANTERIOR) / MONTO_MES_ANTERIOR * 100, 2)
    ) AS VAR_PCT
FROM con_anterior;

-- Vista por área y mes
CREATE OR REPLACE VIEW DATAFINANCE.GOLD.KPI_AREA_MENSUAL AS
WITH agregado AS (
    SELECT
        MES,
        ANIO_MES,
        YEAR(MES) AS ANIO,
        MONTH(MES) AS NUMERO_MES,
        AREA,
        TIPO,
        COUNT(*) AS TOTAL_TRANSACCIONES,
        ROUND(SUM(MONTO), 2) AS MONTO_TOTAL
    FROM DATAFINANCE.SILVER.TRANSACCIONES
    GROUP BY MES, ANIO_MES, YEAR(MES), MONTH(MES), AREA, TIPO
),
con_anterior AS (
    SELECT
        *,
        LAG(MONTO_TOTAL) OVER (
            PARTITION BY AREA, TIPO
            ORDER BY MES
        ) AS MONTO_MES_ANTERIOR
    FROM agregado
)
SELECT
    MES,
    ANIO_MES,
    ANIO,
    NUMERO_MES,
    AREA,
    TIPO,
    TOTAL_TRANSACCIONES,
    MONTO_TOTAL,
    MONTO_MES_ANTERIOR,
    ROUND(MONTO_TOTAL - MONTO_MES_ANTERIOR, 2) AS VAR_ABS,
    IFF(
        MONTO_MES_ANTERIOR IS NULL OR MONTO_MES_ANTERIOR = 0,
        NULL,
        ROUND((MONTO_TOTAL - MONTO_MES_ANTERIOR) / MONTO_MES_ANTERIOR * 100, 2)
    ) AS VAR_PCT
FROM con_anterior;
