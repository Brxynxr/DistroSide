-- 8. Vista analítica para cuadre consolidado diario
CREATE OR REPLACE VIEW DATAFINANCE.PUBLIC.V_CUADRE_DIARIO_CONSOLIDADO AS
WITH ventas_dia AS (
    SELECT
        FECHA,
        COUNT(*) AS TOTAL_TRANSACCIONES,
        ROUND(SUM(IFF(CATEGORIA = 'VENTA CONTADO', MONTO, 0)), 2) AS VENTAS_CONTADO,
        ROUND(SUM(IFF(CATEGORIA = 'VENTA CREDITO', MONTO, 0)), 2) AS VENTAS_CREDITO,
        ROUND(SUM(IFF(CATEGORIA = 'SERVICIOS', MONTO, 0)), 2) AS SERVICIOS,
        ROUND(SUM(MONTO), 2) AS TOTAL_VENTAS
    FROM DATAFINANCE.PUBLIC.TRANSACCIONES
    WHERE TIPO = 'INGRESO'
    GROUP BY FECHA
)
SELECT
    FECHA,
    TOTAL_VENTAS,
    VENTAS_CONTADO,
    VENTAS_CREDITO,
    SERVICIOS,
    TOTAL_TRANSACCIONES,
    ROUND((VENTAS_CONTADO / NULLIF(TOTAL_VENTAS, 0)) * 100, 2) AS RATIO_CONTADO_PCT,
    ROUND((VENTAS_CREDITO / NULLIF(TOTAL_VENTAS, 0)) * 100, 2) AS RATIO_CREDITO_PCT,
    ROUND((SERVICIOS / NULLIF(TOTAL_VENTAS, 0)) * 100, 2) AS RATIO_SERVICIOS_PCT,
    CASE
        WHEN (VENTAS_CONTADO / NULLIF(TOTAL_VENTAS, 0)) >= 0.45 THEN 'OPTIMA'
        WHEN (VENTAS_CONTADO / NULLIF(TOTAL_VENTAS, 0)) >= 0.35 THEN 'ADVERTENCIA'
        ELSE 'CRITICA'
    END AS ESTADO_LIQUIDEZ
FROM ventas_dia
ORDER BY FECHA DESC;



