-- Esquema consolidado DataFinance AI en DATAFINANCE.PUBLIC
-- Centraliza transacciones limpias, KPIs precalculados, vistas analíticas y reportes.

CREATE SCHEMA IF NOT EXISTS DATAFINANCE.PUBLIC;

-- 1. Tabla de transacciones limpias
CREATE TABLE IF NOT EXISTS DATAFINANCE.PUBLIC.TRANSACCIONES (
    ID_TRANSACCION VARCHAR PRIMARY KEY,
    FECHA DATE,
    ANIO NUMBER,
    MES DATE,
    ANIO_MES VARCHAR,
    TIPO VARCHAR,
    CATEGORIA VARCHAR,
    AREA VARCHAR,
    MONTO NUMBER(14,2),
    DESCRIPCION VARCHAR
);

-- 2. Tabla consolidada de KPIs mensuales
CREATE TABLE IF NOT EXISTS DATAFINANCE.PUBLIC.KPI_MENSUAL (
    MES DATE PRIMARY KEY,
    ANIO_MES VARCHAR,
    ANIO NUMBER,
    NUMERO_MES NUMBER,
    TOTAL_TRANSACCIONES NUMBER,
    INGRESOS NUMBER(14,2),
    GASTOS NUMBER(14,2),
    UTILIDAD NUMBER(14,2),
    MARGEN_PCT NUMBER(7,2),
    INGRESOS_MES_ANTERIOR NUMBER(14,2),
    GASTOS_MES_ANTERIOR NUMBER(14,2),
    UTILIDAD_MES_ANTERIOR NUMBER(14,2),
    VAR_INGRESOS_ABS NUMBER(14,2),
    VAR_INGRESOS_PCT NUMBER(7,2),
    VAR_GASTOS_ABS NUMBER(14,2),
    VAR_GASTOS_PCT NUMBER(7,2),
    VAR_UTILIDAD_ABS NUMBER(14,2),
    VAR_UTILIDAD_PCT NUMBER(7,2),
    ACTUALIZADO_EN TIMESTAMP_NTZ
);

-- 3. Vista analítica por categoría
CREATE OR REPLACE VIEW DATAFINANCE.PUBLIC.KPI_CATEGORIA_MENSUAL AS
WITH agregado AS (
    SELECT
        MES,
        ANIO_MES,
        YEAR(MES) AS ANIO,
        MONTH(MES) AS NUMERO_MES,
        TIPO,
        CATEGORIA,
        COUNT(*) AS TOTAL_TRANSACCIONES,
        ROUND(SUM(MONTO), 2) AS MONTO_TOTAL
    FROM DATAFINANCE.PUBLIC.TRANSACCIONES
    GROUP BY MES, ANIO_MES, YEAR(MES), MONTH(MES), TIPO, CATEGORIA
),
con_anterior AS (
    SELECT
        *,
        LAG(MONTO_TOTAL) OVER (
            PARTITION BY TIPO, CATEGORIA
            ORDER BY MES
        ) AS MONTO_MES_ANTERIOR
    FROM agregado
)
SELECT
    MES,
    ANIO_MES,
    ANIO,
    NUMERO_MES,
    TIPO,
    CATEGORIA,
    TOTAL_TRANSACCIONES,
    MONTO_TOTAL,
    MONTO_MES_ANTERIOR,
    ROUND(MONTO_TOTAL - MONTO_MES_ANTERIOR, 2) AS VAR_ABS,
    IFF(
        MONTO_MES_ANTERIOR IS NULL OR MONTO_MES_ANTERIOR = 0,
        NULL,
        ROUND((MONTO_TOTAL - MONTO_MES_ANTERIOR) / MONTO_MES_ANTERIOR * 100, 2)
    ) AS VAR_PCT
FROM con_anterior;

-- 4. Vista analítica por área
CREATE OR REPLACE VIEW DATAFINANCE.PUBLIC.KPI_AREA_MENSUAL AS
WITH agregado AS (
    SELECT
        MES,
        ANIO_MES,
        YEAR(MES) AS ANIO,
        MONTH(MES) AS NUMERO_MES,
        AREA,
        TIPO,
        COUNT(*) AS TOTAL_TRANSACCIONES,
        ROUND(SUM(MONTO), 2) AS MONTO_TOTAL
    FROM DATAFINANCE.PUBLIC.TRANSACCIONES
    GROUP BY MES, ANIO_MES, YEAR(MES), MONTH(MES), AREA, TIPO
),
con_anterior AS (
    SELECT
        *,
        LAG(MONTO_TOTAL) OVER (
            PARTITION BY AREA, TIPO
            ORDER BY MES
        ) AS MONTO_MES_ANTERIOR
    FROM agregado
)
SELECT
    MES,
    ANIO_MES,
    ANIO,
    NUMERO_MES,
    AREA,
    TIPO,
    TOTAL_TRANSACCIONES,
    MONTO_TOTAL,
    MONTO_MES_ANTERIOR,
    ROUND(MONTO_TOTAL - MONTO_MES_ANTERIOR, 2) AS VAR_ABS,
    IFF(
        MONTO_MES_ANTERIOR IS NULL OR MONTO_MES_ANTERIOR = 0,
        NULL,
        ROUND((MONTO_TOTAL - MONTO_MES_ANTERIOR) / MONTO_MES_ANTERIOR * 100, 2)
    ) AS VAR_PCT
FROM con_anterior;
